function svgOf(shape){
  var d=Object.prototype.hasOwnProperty.call(SHAPES,shape)?SHAPES[shape]:SHAPES.rect;
  return '<svg viewBox="0 0 100 100" preserveAspectRatio="none"><path class="o" d="'+d+'"/><path class="m" d="'+d+'"/></svg>';
}
function bboxOf(pts){
  var x1=1,y1=1,x2=0,y2=0;
  pts.forEach(function(p){x1=Math.min(x1,p.x);y1=Math.min(y1,p.y);x2=Math.max(x2,p.x+p.w);y2=Math.max(y2,p.y+p.h)});
  return {x:x1,y:y1,w:x2-x1,h:y2-y1};
}
