  function playSound(st){
    if(muted||!hasSound(st)) return;
    try{
      if(st.h.audio){aud.src=st.h.audio; aud.currentTime=0; var pr=aud.play(); if(pr&&pr.catch)pr.catch(function(){});}
      else{var u=new SpeechSynthesisUtterance(st.h.tip); u.lang=rtl?'ar':'en'; speechSynthesis.speak(u);}
    }catch(e){}
  }
